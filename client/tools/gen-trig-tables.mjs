// Generator for the deterministic fp-trig lookup tables (design/06 "fp-trig").
//
// WHY THIS EXISTS — the determinism rule for trig:
//   Math.sin/cos are NOT bit-identical across JS engines (WeChat JavaScriptCore
//   vs V8 vs desktop browsers). Computing the table at runtime with Math.sin and
//   rounding to integer fp would occasionally differ by 1 ULP across engines →
//   desync. So the table is generated OFFLINE here and committed as integer
//   literal data (src/engine/math/trig.table.ts). Runtime code only does integer
//   arithmetic (table lookup + linear interpolation), which IS deterministic.
//
// Re-run after changing FP_SCALE / BRAD_FULL / sample counts, then commit the
// regenerated trig.table.ts. Any change to the emitted numbers can diverge old
// replays → bump ENGINE_VERSION (design/08).
//
//   node tools/gen-trig-tables.mjs
//
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const FP_SCALE = 1000; // must match math/fixed.ts
const BRAD_FULL = 65536; // 16-bit binary radians, must match math/trig.ts

// Sample counts. Linear-interp error of sin at N=256 is < 0.005 fp — negligible.
const SIN_N = 256; // samples over a quarter wave [0, PI/2]
const ATAN_M = 256; // samples of atan over slope [0, 1] (→ 0..45° → 0..8192 brad)

// Quarter sine wave, inclusive of both endpoints: SIN_N + 1 samples.
// Value at k = round(sin(k/SIN_N * PI/2) * FP_SCALE), in [0, FP_SCALE].
const sin = [];
for (let k = 0; k <= SIN_N; k++) {
  const angle = (k / SIN_N) * (Math.PI / 2);
  sin.push(Math.round(Math.sin(angle) * FP_SCALE));
}

// arctan of slope t = i/ATAN_M for i in [0, ATAN_M], value in brad over [0, 45°].
// atan(1) = 45° = BRAD_FULL / 8 = 8192.
const atan = [];
for (let i = 0; i <= ATAN_M; i++) {
  const t = i / ATAN_M;
  const brad = Math.round((Math.atan(t) / (2 * Math.PI)) * BRAD_FULL);
  atan.push(brad);
}

const fmt = (arr) => {
  // 12 numbers per line for a readable diff.
  const lines = [];
  for (let i = 0; i < arr.length; i += 12) {
    lines.push('  ' + arr.slice(i, i + 12).join(', ') + ',');
  }
  return lines.join('\n');
};

const out = `// GENERATED by tools/gen-trig-tables.mjs — DO NOT EDIT BY HAND.
// Deterministic fp-trig lookup data (design/06). Integer literals so every JS
// engine reads identical bytes; runtime does integer interp only. Regenerate via
// \`node tools/gen-trig-tables.mjs\` and commit; number changes bump ENGINE_VERSION.

/** Samples over a quarter wave [0, PI/2]; length = SIN_N + 1. Values in [0, FP_SCALE]. */
export const SIN_N = ${SIN_N};
export const SIN_QUARTER: readonly number[] = [
${fmt(sin)}
];

/** atan(i/ATAN_M) in brad over slope [0,1] (0..45° = 0..8192); length = ATAN_M + 1. */
export const ATAN_M = ${ATAN_M};
export const ATAN_QUARTER: readonly number[] = [
${fmt(atan)}
];
`;

const dir = dirname(fileURLToPath(import.meta.url));
const dest = join(dir, '..', 'src', 'engine', 'math', 'trig.table.ts');
writeFileSync(dest, out);
console.log(`wrote ${dest}\n  SIN_QUARTER: ${sin.length} samples\n  ATAN_QUARTER: ${atan.length} samples`);
